def content_feedback(subject: Subject, stem: str, work: str = "") -> ContentFeedback:
    text = f"{stem}\n{work}".lower()
    candidates: list[tuple[int, int, ContentFeedback]] = []
    combined_rules = [*RULES.get(subject, []), *EXTRA_RULES.get(subject, [])]
    for index, (markers, feedback) in enumerate(combined_rules):
        score = sum(max(1, len(marker)) for marker in markers if marker.lower() in text)
        if score:
            candidates.append((score, -index, feedback))
    if candidates:
        selected = max(candidates, key=lambda item: (item[0], item[1]))[2]
        concept, prompt = TOPIC_DETAILS.get(
            selected.topic,
            (
                f"这一内容属于“{selected.topic}”，需要把概念条件、题干证据和推理步骤对应起来。",
                "请先指出题干中最关键的一个条件，以及它限制了什么。",
            ),
        )
        return replace(selected, concept=concept, next_prompt=prompt)
    return ContentFeedback(
        topic=f"{subject.value}综合题",
        method=SUBJECT_POLICIES[subject],
        checkpoint="题干条件、所求目标与当前步骤使用的方法是否一一对应",
        concept="当前信息还不足以锁定唯一知识点，需要先从关键词、条件和设问中缩小范围。",
        next_prompt="请补充题目原文或指出你想了解的具体概念，我会据此继续分析。",
    )
